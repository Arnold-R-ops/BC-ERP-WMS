        RAISE NOTICE '✓ product_spu 表已创建';
    ELSE
        RAISE NOTICE '⊙ product_spu 表已存在，跳过创建';
    END IF;
END $$;

-- 1.2 修改序列允许手动插入 ID=0
DO $$
BEGIN
    -- 检查列是否为 GENERATED ALWAYS
    IF EXISTS (
        SELECT 1 FROM pg_attribute a
        JOIN pg_class c ON a.attrelid = c.oid
        WHERE c.relname = 'product_spu'
          AND a.attname = 'id'
          AND a.attidentity = 'a'  -- 'a' = ALWAYS
    ) THEN
        ALTER TABLE product_spu ALTER COLUMN id SET GENERATED BY DEFAULT;
        RAISE NOTICE '✓ product_spu.id 序列已修改为 BY DEFAULT';
    ELSE
        RAISE NOTICE '⊙ product_spu.id 序列已是 BY DEFAULT，跳过修改';
    END IF;
END $$;

