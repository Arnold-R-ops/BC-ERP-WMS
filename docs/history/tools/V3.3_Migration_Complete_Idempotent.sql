-- 3.6 删除 batch_code 的所有唯一约束
DO $$
DECLARE
    constraint_rec RECORD;
    dropped_count INTEGER := 0;
BEGIN
    FOR constraint_rec IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'inventory_batch'::regclass
          AND contype = 'u'
          AND conname IN (
              SELECT constraint_name
              FROM information_schema.constraint_column_usage
              WHERE table_name = 'inventory_batch'
                AND column_name = 'batch_code'
          )
    LOOP
        EXECUTE format('ALTER TABLE inventory_batch DROP CONSTRAINT IF EXISTS %I', constraint_rec.conname);
        RAISE NOTICE '✓ 已删除唯一约束: %', constraint_rec.conname;
        dropped_count := dropped_count + 1;
    END LOOP;

    IF dropped_count = 0 THEN
        RAISE NOTICE '⊙ batch_code 上没有唯一约束，跳过删除';
    END IF;
END $$;

-- 3.7 删除 batch_code 的唯一索引
DO $$
DECLARE
    index_rec RECORD;
    dropped_count INTEGER := 0;
BEGIN
    FOR index_rec IN
        SELECT indexname
        FROM pg_indexes
        WHERE tablename = 'inventory_batch'
          AND indexdef LIKE '%UNIQUE%'
          AND indexdef LIKE '%batch_code%'
    LOOP
        EXECUTE format('DROP INDEX IF EXISTS %I', index_rec.indexname);
        RAISE NOTICE '✓ 已删除唯一索引: %', index_rec.indexname;
        dropped_count := dropped_count + 1;
    END LOOP;

    IF dropped_count = 0 THEN
        RAISE NOTICE '⊙ batch_code 上没有唯一索引，跳过删除';
    END IF;
END $$;

